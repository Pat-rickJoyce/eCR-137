#!/usr/bin/env node
/**
 * Generates docs/condition-requirements.md — the human-readable
 * reportability reference (features.md: "Human-Readable Condition
 * Reportability Descriptions") — FROM the rule packs. One direction
 * only: packs are the source of truth; never edit the output.
 * Replaces the old regex-post-processed reportability_requirements.md.
 * Run: node scripts/generate-requirements.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const packDir = join(root, 'rules', 'conditions');
const outFile = join(root, 'docs', 'condition-requirements.md');

const PRED_TEXT = {
    diagnosisInValueSet: p => `patient has a **diagnosis** in ${vs(p)}`,
    problemInValueSet: p => `patient has a${p.status === 'active' ? 'n **active**' : ''} **problem list entry** in ${vs(p)}`,
    labTestInValueSet: p => `patient has a **lab test** in ${vs(p)}`,
    labTestWithResultInValueSet: p => `patient has a **lab test** in ${vs(p)} whose **result value** is in **${p.resultName}** (\`${p.resultOid}\`)`,
    labTestWithInterpretationIn: p => `patient has a **lab test** in ${vs(p)} whose result **interpretation** is one of ${(p.codes || []).join(', ')}`,
    labResultInValueSet: p => `patient has a **lab result value** in ${vs(p)}`,
    labInterpretationIn: p => `lab result **interpretation** is one of ${(p.codes || []).join(', ')} (${p.name || 'abnormal'})`,
    medicationInValueSet: p => `patient has a **medication** in ${vs(p)}`,
    ageComparison: p => `patient **age ${p.op} ${p.value} ${p.unit}**`,
    pregnancyStatus: p => `patient pregnancy status is **${(p && p.value) || 'pregnant'}**`,
    encounterType: p => `patient has an **encounter type** in ${vs(p)}`,
    evidencePresent: p => `evidence of kind \`${p.kind}\` is present`,
    chiefComplaintMatches: p => `patient has a **chief complaint** of "${p.text}" *(not yet implemented — skips)*`,
    epidemiologicalFact: p => `epidemiological fact: ${p.fact} *(not yet implemented — skips)*`,
    withinTimebox: () => `event date is within the reporting timebox *(not yet implemented — skips)*`
};

function vs(p) {
    return p.oid ? `**${p.name}** (\`${p.oid}\`)` : `**${p.name}** *(no codes in release — skips)*`;
}

function renderNode(node, indent) {
    const pad = '  '.repeat(indent);
    const gate = node.gate ? ' *(gate)*' : '';
    if (node.predicate) {
        const fn = PRED_TEXT[node.predicate] || (p => `\`${node.predicate}\`(${JSON.stringify(p)})`);
        return `${pad}- ${fn(node.params || {})}${gate}\n`;
    }
    if (node.all) return `${pad}- **ALL** of:${gate}\n` + node.all.map(n => renderNode(n, indent + 1)).join('');
    if (node.any) return `${pad}- **ANY** of:${gate}\n` + node.any.map(n => renderNode(n, indent + 1)).join('');
    if (node.atLeast) return `${pad}- **AT LEAST ${node.atLeast.n}** of:${gate}\n` + node.atLeast.of.map(n => renderNode(n, indent + 1)).join('');
    if (node.not) return `${pad}- **NOT**:\n` + renderNode(node.not, indent + 1);
    return `${pad}- (unknown node)\n`;
}

const files = readdirSync(packDir).filter(f => f.endsWith('.json') && !f.endsWith('.draft.json')).sort();
let md = `# Condition Reportability Requirements

> GENERATED from \`rules/conditions/*.json\` by \`scripts/generate-requirements.mjs\`.
> Do not edit this file; edit the packs. Legend: *(gate)* = constrains but
> cannot alone make a condition reportable; *skips* = declared coverage gap,
> excluded from the verdict and shown as reduced coverage.

`;

for (const f of files) {
    const p = JSON.parse(readFileSync(join(packDir, f), 'utf8'));
    md += `## ${p.name} (\`${p.conditionId}\`)\n\n`;
    md += `| | |\n|---|---|\n`;
    md += `| Pack | \`${p.mnemonic}\` (coverage: **${p.coverage}**) |\n`;
    md += `| Source | ${p.source.document} (RCKMS ${p.source.rckmsVersion || ''} ${p.source.rckmsDate}) |\n`;
    md += `| Terminology | RCTC release ${p.source.rctcRelease} |\n`;
    md += `| Evidence model | ${p.evidenceModel} |\n`;
    md += `| Modified | ${p.modified} |\n\n`;

    for (const rule of p.rules) {
        md += `### ${rule.id}\n\n${rule.description}\n\nReport when:\n\n`;
        md += renderNode(rule.logic, 0);
        md += '\n';
    }

    if (p.gaps && p.gaps.length) {
        md += `### Known gaps (${p.conditionId})\n\n`;
        for (const g of p.gaps) md += `- **${g.valueSet}** — ${g.reason}\n`;
        md += '\n';
    }
}

writeFileSync(outFile, md);
console.log(`Wrote ${outFile} (${files.length} condition(s))`);
