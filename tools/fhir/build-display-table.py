"""Builds js/fhir/display-table.xml from tools/fhir/terminology/.

tx-lookup.json                 preferred displays from tx.fhir.org (lookup-displays.ps1)
profile-pattern-displays.json  displays fixed by eCR 2.1.2 / US Core 3.1.1 profile patterns (win over lookup)
manual-displays.json           displays from validator valid-display lists for codes tx $lookup does not return
"""
import json, os, sys
from xml.sax.saxutils import quoteattr
root = sys.argv[1] if len(sys.argv) > 1 else '.'
t = os.path.join(root, 'tools/fhir/terminology')
def load(n):
    p = os.path.join(t, n)
    return json.load(open(p, encoding='utf-8-sig')) if os.path.exists(p) else []
table = {}
for x in load('tx-lookup.json'):
    table[(x['system'], x['code'])] = x.get('display') if x.get('status') == 'ok' else None
for x in load('manual-displays.json') + load('profile-pattern-displays.json'):
    table[(x['system'], x['code'])] = x['display']
lines = ['<?xml version="1.0" encoding="UTF-8"?>',
         '<!-- GENERATED by tools/fhir/build-display-table.py. Verified coding displays for eCR-137 FHIR output. Entries without @display are codes the terminology server does not know. -->',
         '<displays>']
for (s, c), d in sorted(table.items()):
    lines.append(f'  <entry system={quoteattr(s)} code={quoteattr(c)}' + (f' display={quoteattr(d)}' if d else '') + '/>')
lines.append('</displays>')
open(os.path.join(root, 'js/fhir/display-table.xml'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print(len(table), 'entries')
