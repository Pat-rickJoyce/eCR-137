#!/usr/bin/env python3
"""Build js/fhir/rr-condition-codes.js: the SNOMED CT reportable condition code for each condition pack.

Usage (repo root): python3 tools/fhir/build-rr-condition-codes.py

Source: assets/data/RCTC_Release (2025-03-18).xlsx. Each RCTC worksheet opens with a table that assigns every
trigger code value set its reportable condition (SNOMED CT code and name). A condition pack in rules/conditions
names the value sets its rules use; the pack's condition code is the condition most of those value sets map to.
The FHIR RR uses the code as the Relevant Reportable Condition Observation value. Packs whose value sets are not
in the release have no entry; the RR builder then uses the matched SNOMED CT diagnosis or problem.
The display is the verified display from js/fhir/display-table.xml where the code is listed, else the RCTC name.
"""
import collections, glob, json, os, re
import xml.etree.ElementTree as ET
import openpyxl

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
RCTC = os.path.join(ROOT, 'assets', 'data', 'RCTC_Release (2025-03-18).xlsx')
OUT = os.path.join(ROOT, 'js', 'fhir', 'rr-condition-codes.js')
DISPLAYS = os.path.join(ROOT, 'js', 'fhir', 'display-table.xml')


def norm(s):
    return re.sub(r'\s+', ' ', str(s).replace('\xa0', ' ')).strip().lower()


def vs_conditions():
    wb = openpyxl.load_workbook(RCTC, read_only=True)
    out = {}
    for sheet in wb.sheetnames[2:]:
        for r in wb[sheet].iter_rows(values_only=True):
            if not r or len(r) < 8 or not isinstance(r[0], str) or r[0].startswith('2.16.'):
                continue
            code, name, system = r[1], r[2], r[7]
            if system == 'SNOMEDCT' and re.fullmatch(r'\d{6,18}', str(code or '')) and name:
                out.setdefault(norm(r[0]), []).append((str(code), str(name).strip()))
    return out


def pack_value_set_names(pack):
    names = []

    def walk(o):
        if isinstance(o, dict):
            p = o.get('params')
            if isinstance(p, dict) and p.get('name'):
                names.append(p['name'])
            for v in o.values():
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)
    walk(pack)
    return names


def main():
    vs = vs_conditions()
    verified = {e.get('code'): e.get('display') for e in ET.parse(DISPLAYS).getroot()
                if e.get('system') == 'http://snomed.info/sct' and e.get('display')}
    codes = {}
    for f in sorted(glob.glob(os.path.join(ROOT, 'rules', 'conditions', '*.json'))):
        pack = json.load(open(f, encoding='utf-8'))
        votes = collections.Counter()
        for n in pack_value_set_names(pack):
            for c in dict.fromkeys(vs.get(norm(n), [])):
                votes[c] += 1
        if votes:
            (code, display), _ = votes.most_common(1)[0]
            codes[pack['conditionId']] = {'code': code, 'display': verified.get(code, display)}
    js = ('// Generated by tools/fhir/build-rr-condition-codes.py from RCTC_Release (2025-03-18). Do not edit.\n'
          'window.ECR137_RR_CONDITION_CODES = ' + json.dumps(codes, indent=1, sort_keys=True) + ';\n')
    open(OUT, 'w', encoding='utf-8', newline='\r\n').write(js)
    print(OUT, len(codes), 'conditions')


if __name__ == '__main__':
    main()
