#!/usr/bin/env python3
"""Build js/fhir/ig-notes.js: what the implementation guides say about each profile and Composition section.

Usage: build-ig-notes.py <hl7.fhir.us.ecr#2.1.2 package dir> <hl7.fhir.us.core#3.1.1 package dir> <hl7.fhir.us.core#4.0.0 package dir>

For every profile: title, guide, page URL, the first sentence of its description, the top-level elements it
requires (min 1 or more) and the ones it marks Must Support. For the eicr-composition and rr-composition
sections: slice name, cardinality, the first sentence of the definition and the entry slices with their
cardinality and target profiles. js/fhir/fhir-annotate.js writes these into the FHIR Bundle comments.
"""
import glob, json, os, re, sys

GUIDES = [
    ('eCR 2.1.2', 'https://hl7.org/fhir/us/ecr/2.1.2/'),
    ('US Core 3.1.1', 'https://hl7.org/fhir/us/core/STU3.1.1/'),
    ('US Core 4.0.0', 'https://hl7.org/fhir/us/core/STU4/'),
]
SKIP = {'id', 'meta', 'implicitRules', 'language', 'text', 'contained', 'modifierExtension'}


def plain(md):
    s = re.sub(r'\[([^\]]+)\]\([^)]*\)', r'\1', md or '')
    s = re.sub(r'<[^>]+>', ' ', s)
    s = re.sub(r'[*_`#]+', '', s)
    s = re.sub(r'\s+', ' ', s).strip()
    return s


def first_sentence(md, limit=320):
    s = plain(md)
    m = re.search(r'^(.+?[.;])(\s|$)', s)
    s = m.group(1) if m else s
    return s if len(s) <= limit else s[:limit].rsplit(' ', 1)[0] + '...'


def label(e):
    name = e['path'].split('.', 1)[1]
    return name + (':' + e['sliceName'] if e.get('sliceName') else '')


def tail(url):
    return url.rstrip('/').split('/')[-1]


def profile_note(sd, guide, base):
    els = sd['snapshot']['element']
    top = [e for e in els if e['path'].count('.') == 1 and e['path'].split('.', 1)[1] not in SKIP]
    req, ms = [], []
    for e in top:
        n = label(e)
        if e.get('max') == '0':
            continue
        if e.get('min', 0) >= 1:
            req.append(n)
        elif e.get('mustSupport'):
            ms.append(n)
    sliced = {n.split(':')[0] for n in req + ms if ':' in n}
    req = [n for n in req if n not in sliced]
    ms = [n for n in ms if n not in sliced]
    return {'title': sd.get('title') or sd['name'], 'guide': guide, 'url': f"{base}StructureDefinition-{sd['id']}.html",
            'summary': first_sentence(sd.get('description', '')), 'required': req, 'mustSupport': ms}


def section_notes(sd):
    els = sd['snapshot']['element']
    out = {}
    for e in els:
        if e['path'] != 'Composition.section' or not e.get('sliceName'):
            continue
        sid = e['id']
        code = None
        for c in els:
            if c['id'] == sid + '.code':
                cc = c.get('patternCodeableConcept') or c.get('fixedCodeableConcept') or {}
                codes = [x.get('code') for x in cc.get('coding', []) if x.get('code')]
                code = codes[0] if codes else None
        entries = []
        for c in els:
            if c['id'].startswith(sid + '.entry:') and c['id'].count(':') == 2 and c.get('sliceName'):
                targets = [tail(t) for ty in c.get('type', []) for t in ty.get('targetProfile', [])]
                entries.append({'slice': c['sliceName'], 'card': f"{c.get('min', 0)}..{c.get('max', '*')}", 'targets': targets})
        if not entries:
            for c in els:
                if c['id'] == sid + '.entry':
                    targets = [tail(t) for ty in c.get('type', []) for t in ty.get('targetProfile', [])]
                    entries.append({'slice': '', 'card': f"{c.get('min', 0)}..{c.get('max', '*')}", 'targets': targets})
        if code:
            out[code] = {'slice': e['sliceName'], 'card': f"{e.get('min', 0)}..{e.get('max', '*')}",
                         'short': plain(e.get('short', '')), 'summary': first_sentence(e.get('definition', '')), 'entries': entries}
    return out


def main(dirs, out):
    profiles, sections = {}, {}
    for (guide, base), d in zip(GUIDES, dirs):
        for f in sorted(glob.glob(os.path.join(d, 'StructureDefinition-*.json'))):
            sd = json.load(open(f, encoding='utf-8-sig'))
            if sd.get('kind') != 'resource' or sd.get('derivation') != 'constraint':
                continue
            key = tail(sd['url'])
            if key in profiles:
                continue
            profiles[key] = profile_note(sd, guide, base)
            if key in ('eicr-composition', 'rr-composition'):
                sections[key] = section_notes(sd)
    js = ('// Generated by tools/fhir/build-ig-notes.py from hl7.fhir.us.ecr#2.1.2, hl7.fhir.us.core#3.1.1 and #4.0.0. Do not edit.\n'
          'window.ECR137_IG_NOTES = ' + json.dumps({'profiles': profiles, 'sections': sections}, indent=1, ensure_ascii=False) + ';\n')
    open(out, 'w', encoding='utf-8', newline='\r\n').write(js)
    print(out, len(profiles), 'profiles,', {k: len(v) for k, v in sections.items()}, 'sections')


if __name__ == '__main__':
    here = os.path.dirname(os.path.abspath(__file__))
    main(sys.argv[1:4], os.path.join(here, '..', '..', 'js', 'fhir', 'ig-notes.js'))
