#!/usr/bin/env python3
"""Build js/fhir/fhir-r4-json-types.js from the FHIR R4 (4.0.1) StructureDefinitions.

Usage: build-json-typemap.py <dir with hl7.fhir.r4.core#4.0.1 StructureDefinition-*.json> [out]

The map drives the FHIR XML to JSON serializer: for every resource, data type and
backbone element it lists each child element name (choice elements expanded to
their XML names) with its type and whether JSON represents it as an array.
"""
import glob, json, os, sys

FT = 'http://hl7.org/fhir/StructureDefinition/structuredefinition-fhir-type'


def tcode(t):
    c = t['code']
    if c.startswith('http://hl7.org/fhirpath/System.'):
        for x in t.get('extension', []):
            if x['url'] == FT:
                return x['valueUrl']
        return c.rsplit('.', 1)[1].lower()
    return c


def main(src, out):
    sds = [json.load(open(f, encoding='utf-8')) for f in glob.glob(os.path.join(src, 'StructureDefinition-*.json'))]
    sds = [s for s in sds if s.get('derivation') == 'specialization' and s['kind'] in ('resource', 'complex-type', 'primitive-type')]
    prims = sorted(s['type'] for s in sds if s['kind'] == 'primitive-type')
    resources = sorted(s['type'] for s in sds if s['kind'] == 'resource')
    types = {}
    for s in sorted(sds, key=lambda s: s['type']):
        if s['kind'] == 'primitive-type':
            continue
        els = s['snapshot']['element']
        paths = {e['path'] for e in els}
        for e in els:
            path = e['path']
            if '.' not in path:
                continue
            parent, name = path.rsplit('.', 1)
            arr = e.get('base', {}).get('max', e.get('max')) != '1'
            if 'contentReference' in e:
                tys = [e['contentReference'].lstrip('#')]
            else:
                tys = [tcode(t) for t in e.get('type', [])]
                if any(p.startswith(path + '.') for p in paths) and tys and tys[0] in ('BackboneElement', 'Element'):
                    tys = [path]
            ent = types.setdefault(parent, {})
            if name.endswith('[x]'):
                base = name[:-3]
                for t in tys:
                    ent[base + t[0].upper() + t[1:]] = t + ('*' if arr else '')
            else:
                ent[name] = tys[0] + ('*' if arr else '')
    js = ('// Generated by tools/fhir/build-json-typemap.py from hl7.fhir.r4.core#4.0.1. Do not edit.\n'
          'window.ECR137_FHIR_R4_TYPES = ' + json.dumps({'primitives': prims, 'resources': resources, 'types': types},
                                                       separators=(',', ':'), sort_keys=False) + ';\n')
    open(out, 'w', encoding='utf-8', newline='\r\n').write(js)
    print(out, len(js), 'bytes;', len(types), 'type keys')


if __name__ == '__main__':
    here = os.path.dirname(os.path.abspath(__file__))
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, '..', '..', 'js', 'fhir', 'fhir-r4-json-types.js'))
